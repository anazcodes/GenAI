dataloader = DataLoader(
    tokens_pad, batch_size=BATCH_SIZE, shuffle=False,
    collate_fn=make_collate_fn(vocab, CONTEXT_SIZE, device)
    )


model = NGramLanguageModeler(len(vocab), EMBEDDING_DIM, CONTEXT_SIZE).to(device)

