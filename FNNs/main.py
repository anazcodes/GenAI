print(generated_song)



# Training
criterion = torch.nn.CrossEntropyLoss()

print("numpy version:", np.__version__)


my_loss_list = []
model_names = ["2-gram", "4-gram", "8-gram"]
tsne_fig_paths = ["FNNs/fig1", "FNNs/fig2", "FNNs/fig3"]

# Train one NGramLanguageModeler per context size, saving its checkpoint and TSNE plot
for context_size, fig_path in zip([2, 4, 8], tsne_fig_paths):
    CONTEXT_SIZE = context_size
    dataloader = DataLoader(
        tokens_pad, batch_size=BATCH_SIZE, shuffle=False,
        collate_fn=make_collate_fn(vocab, CONTEXT_SIZE, device)
        )

    # Create an instance of the NGramLanguageModeler class with specified parameters
    model = NGramLanguageModeler(len(vocab), EMBEDDING_DIM, CONTEXT_SIZE).to(device)

    # Define the optimizer for training the model, using stochastic gradient descent (SGD)
    optimizer = optim.SGD(model.parameters(), lr=0.01)

    # Set up a learning rate scheduler using StepLR to adjust the learning rate during training
    scheduler = torch.optim.lr_scheduler.StepLR(optimizer, step_size=1.0, gamma=0.1)

    my_loss = train(dataloader, model, song, optimizer, criterion, vocab, tokens, CONTEXT_SIZE, device)

    save_path = f'FNNs/{CONTEXT_SIZE}gram.pth'
    torch.save(model.state_dict(), save_path)
    my_loss_list.append(my_loss)

    plot_tsne_embeddings(model, index_to_token, fig_path)


plot_metric_comparison(my_loss_list, model_names, "Cross-entropy Loss", "FNNs/fig4")


#  Perplexity
perplexities = [np.exp(my_loss) for my_loss in my_loss_list]
plot_metric_comparison(perplexities, model_names, "Perplexity", "FNNs/fig5")
