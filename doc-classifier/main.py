def label_pipeline(x):
    return int(x)- 1

# In PyTorch, the collate_fn function is used in conjunction with data loaders to customize the way batches are created from individual samples.
# The provided code defines a collate_batch function in PyTorch, which is used with data loaders to customize batch creation from individual samples.
# It processes a batch of data, including labels and text sequences. 
# It applies the label_pipeline and text_pipeline functions to preprocess the labels and texts,respectively.
# The processed data is then converted into PyTorch tensors and returned as a tuple containing the label tensors, text tensors, 
# and offsets tensor representing the starting position of each text sequence in the combined tensor. 
# The function also ensures that the returned tensors are moved to the specified device (e.g., GPU) for efficient computation.

def collate_batch(batch):
    label_list, text_list, offsets = [], [], [0]
    for _label, _text in batch:
        label_list.append(label_pipeline(_label))
        processed_text = torch.tensor(text_pipeline(_text), dtype = torch.int64)
        text_list.append(processed_text)
        offsets.append(processed_text.size(0))
    
    label_list = torch.tensor(label_list, dtype = torch.int64)
    offsets = torch.tensor(offsets[:-1]).cumsum(dim= 0)
    text_list = torch.cat(text_list)
    return label_list.to(device), text_list.to(device), offsets.to(device)

